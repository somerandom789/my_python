# Написати програму, яка обчислює середнє арифметичне елементів списку.
# Середнім арифметичним кількох чисел називається їх сума, поділена на їх
# кількість. Результат округлити до двох знаків після десяткової крапки.
#
# Вхідні дані:
#
# 3 5 1 8 4
#
# Вихідні дані:
#
# 4.20

numbers = list(map(int, input("Enter numbers: ").split()))
total_sum = sum(numbers)
count = len(numbers)
average = total_sum / count
print(f"{average:.2f}")