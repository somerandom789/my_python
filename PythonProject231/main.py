# Написати програму, яка приймає на вхід послідовність з цілих чисел, після чого
# друкує значення всіх її елементів, піднесені до квадрату.
#
# Вхідні дані:
#
# 1 2 3 4 5 6 7 8 9
#
# Вихідні дані:
#
# 1 4 9 16 25 36 49 64 81

numbers = list(map(int, input("Enter numbers: ").split()))
for it in numbers:
    print(it ** 2, end=" ")